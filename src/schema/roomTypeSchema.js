// ─────────────────────────────────────────────────────────────────────────────
// ROOM TYPE SCHEMA — Joi validation
// Entity: RoomType | Table: room_type
// ─────────────────────────────────────────────────────────────────────────────
//
// Request field flow:
//   roomTypeId → name → description → pricePerNight → maxOccupancy → amenities
//
// `roomTypeId` is used for lookups; the create payload starts at `name`
// because the database generates the ID. Timestamps are generated as well.
// Attach a schema to a route with validatorHandler(schema, "body").
//
// Model/migration constraints:
//   roomTypeId        INTEGER PK                   → lookup identifier
//   name              VARCHAR(50) NOT NULL UNIQUE
//   description       TEXT NOT NULL
//   pricePerNight     DECIMAL(10,2), 10–10000
//   maxOccupancy      SMALLINT, 1–10
//   amenities         JSONB NOT NULL
//
// Regex checks string shape only. Joi number rules validate the numeric
// fields. The database remains responsible for uniqueness and persistence;
// a Joi schema has no effect until a route applies it with validatorHandler.
// ─────────────────────────────────────────────────────────────────────────────

import Joi from "joi";
import {
  roomTypeAmenity,
  roomTypeDescription,
  roomTypeId,
  roomTypeName,
} from "../utils/RegEx/roomTypeRegEx.js";

export const joiRoomTypeId = Joi.string().pattern(roomTypeId).messages({
  "string.base": "The room type identifier must be a string.",
  "string.pattern.base":
    "The room type identifier must contain 1 to 10 digits.",
});

export const joiRoomTypeName = Joi.string()
  .max(50)
  .pattern(roomTypeName)
  .messages({
    "string.base": "The room type name must be a string.",
    "string.max": "The room type name must not exceed 50 characters.",
    "string.pattern.base":
      "The room type name must contain letters or numbers, with single spaces, apostrophes, or hyphens between words.",
  });

export const joiRoomTypeDescription = Joi.string()
  .pattern(roomTypeDescription)
  .messages({
    "string.base": "The room type description must be a string.",
    "string.pattern.base":
      "The room type description must contain at least one non-whitespace character.",
  });

// Require a JSON number (not a numeric string) with at most two decimal places.
export const joiRoomTypePricePerNight = Joi.number()
  .strict()
  .precision(2)
  .min(10)
  .max(10000)
  .messages({
    "number.base": "The price per night must be a number.",
    "number.precision":
      "The price per night must have no more than 2 decimal places.",
    "number.min": "The price per night must be at least 10.",
    "number.max": "The price per night must not exceed 10000.",
  });

// Occupancy is a whole number from 1 through 10, matching the DB constraint.
export const joiRoomTypeMaxOccupancy = Joi.number()
  .integer()
  .min(1)
  .max(10)
  .messages({
    "number.base": "The maximum occupancy must be a number.",
    "number.integer": "The maximum occupancy must be a whole number.",
    "number.min": "The maximum occupancy must be at least 1.",
    "number.max": "The maximum occupancy must not exceed 10.",
  });

// Each amenity is a lowercase identifier (for example, "private_bathroom").
// This validates the array and each item, but does not restrict values to a
// fixed catalog of supported amenities.
export const joiRoomTypeAmenities = Joi.array()
  .items(
    Joi.string().pattern(roomTypeAmenity).messages({
      "string.base": "Each amenity must be a string.",
      "string.pattern.base":
        "Amenities must start with a lowercase letter and contain only lowercase letters, digits, or underscores.",
    }),
  )
  .messages({
    "array.base": "Amenities must be an array of strings.",
  });

export const roomTypeSchema = {
  // Lookup payload: { roomTypeId: "12" }. IDs are strings in request bodies.
  getRoomTypeById: Joi.object({
    roomTypeId: joiRoomTypeId.required(),
  }),

  // Create payload: name, description, pricePerNight, maxOccupancy, amenities.
  // ID and timestamps are generated by the database.
  newRoomTypeData: Joi.object({
    name: joiRoomTypeName.required(),
    description: joiRoomTypeDescription.required(),
    pricePerNight: joiRoomTypePricePerNight.required(),
    maxOccupancy: joiRoomTypeMaxOccupancy.required(),
    amenities: joiRoomTypeAmenities.required(),
  }),
};
